/**
 * An icon's name in the one spelling the lookup compares: lower case, letters and digits only.
 * @param name "CalendarDays", "calendar-days"…
 * @returns "calendardays"
 */
export const iconKey = (name: string) => name.toLowerCase().replace(/[^a-z0-9]/g, "")

// lucide renames icons now and then (its Building2 says it is BuildingComplex): a name works in both spellings
const BY_NAME = new Map<string, LucideIcon>()
for (const [name, icon] of Object.entries(CONNECTOR_ICONS)) {
  BY_NAME.set(iconKey(name), icon)
  if (icon.displayName) BY_NAME.set(iconKey(icon.displayName), icon)
}

/**
 * The icon for a name the server gave.
 * @param name a lucide icon's name
 * @returns the icon, a plug for a name it doesn't know
 */
export const connectorIcon = (name: string): LucideIcon => BY_NAME.get(iconKey(name)) ?? Plug
